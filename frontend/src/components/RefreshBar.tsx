/**
 * Тонкая полоса поверх контента, пока страница перезапрашивает данные.
 *
 * Нужна потому, что обновление данных больше не подменяет экран сплэшем:
 * без неё pull-to-refresh остался бы вообще без визуального отклика, только
 * с вибрацией. Позиционируется фиксированно, поэтому её можно рендерить
 * в любом месте дерева страницы.
 */
export default function RefreshBar({ active }: { active: boolean }) {
  if (!active) {
    return null;
  }

  return <div className="refresh-bar" role="status" aria-label="Обновление данных" />;
}
